// ============ طبقة تطبيع عامة للنص العامي المصري (قبل أي معالجة تانية) ============
// بتتنادى مرة واحدة في أول السلسلة (سواء النص جاي من كتابة يدوية أو من تفريغ صوت)، وكل حاجة
// بعد كده (التصنيف بالـ AI، واستخراج الأرقام الحتمي) بتشتغل على نفس النسخة المطبّعة. ده بيمنع
// تكرار نفس منطق تحويل الأرقام في أكتر من مكان (كان قبل كده متكرر بين telegram-webhook.js
// وnumberExtraction.js بشكلين مختلفين شوية)، وبيثبّت حاجات شائعة الغلط في تفريغ Whisper.

// ---- أرقام عربية (Eastern Arabic-Indic) وفارسية → أرقام إنجليزية ----
const ARABIC_INDIC = '٠١٢٣٤٥٦٧٨٩';
const PERSIAN = '۰۱۲۳۴۵۶۷۸۹';

function normalizeDigits(text) {
  return String(text || '')
    .replace(/[٠-٩]/g, (d) => String(ARABIC_INDIC.indexOf(d)))
    .replace(/[۰-۹]/g, (d) => String(PERSIAN.indexOf(d)));
}

// ---- تصحيحات إملائية شائعة في تفريغ Whisper للعامية المصرية ----
// دي مش قاموس شامل — بس أشهر الاختلافات اللي بتأثر على فهم المبلغ/العملة نفسها (مش أي كلمة
// عشوائية)، عشان منغيّرش معنى الجملة بالغلط. كل تحويل هنا لازم يكون "حرف/حرفين مختلفين بس"
// عن الصيغة القياسية، مش استبدال كلمة بكلمة تانية مختلفة في المعنى.
const SPELLING_FIXES = [
  [/جنيه[اآ]ت/g, 'جنيه'],   // جنيهات -> جنيه (توحيد صيغة الجمع)
  [/جني[ةه]ً?/g, 'جنيه'],    // جنية / جنيةً -> جنيه
  [/جنيا/g, 'جنيه'],         // خطأ ASR شائع
  [/جنيه ج/g, 'جنيه'],       // "جنيه ج" (تكرار حرف الجيم من "ج.م" ملزوق)
];

export function normalizeEgyptianText(rawText) {
  let text = normalizeDigits(String(rawText || ''));
  for (const [pattern, replacement] of SPELLING_FIXES) {
    text = text.replace(pattern, replacement);
  }
  // مسافات زيادة (شائعة بعد شيل/استبدال كلمات) بتتلخبط بيها بعض الـ regex الحساسة للمسافات
  // في numberExtraction.js، فبنوحدها هنا مرة واحدة.
  return text.replace(/\s+/g, ' ').trim();
}
