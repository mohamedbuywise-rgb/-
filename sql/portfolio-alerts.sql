-- ميزة "نبهني لو تحرك أكثر من %X" — تنبيهات حركة سعر أصل استثماري (صعود أو هبوط)
-- بيتقارن كل يوم في الكرون بين قيمة الأصل النهاردة وقيمته من صورة (snapshot) الأمس،
-- ولو النسبة اللي اتحركت وصلت أو عدّت الحد اللي المستخدم حدده، بيتبعت تنبيه Push + تليجرام.

alter table portfolio_assets
  add column if not exists alert_threshold_pct numeric; -- نسبة الحركة اليومية اللي المستخدم عايز يتنبه لها، مثلاً 10 يعني ±10% في يوم واحد. NULL يعني التنبيه مقفول لهذا الأصل.

comment on column portfolio_assets.alert_threshold_pct is 'نسبة % الحركة اليومية اللي لو الأصل تحركها (صعود أو هبوط) هيتبعت تنبيه Push + تليجرام — NULL يعني التنبيه متعطل لهذا الأصل';
