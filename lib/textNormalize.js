// ============ تحويل الأرقام العربية/الهندية والفارسية (٠١٢٣٤٥٦٧٨٩ / ۰۱۲۳۴۵۶۷۸۹) لأرقام إنجليزية عادية ============
// من غير ده، لو المستخدم كتب "٨٠٠٠٠" بدل "80000"، النص بيروح للـ AI (Groq) زي ما هو والموديل
// أحيانًا بيقرأ العدد أو الأصفار غلط (بيزوّد أو ينقّص صفر) أو يفشل يستخرج مبلغ خالص.
// نفس الدالة بالظبط المستخدمة في بوت تليجرام (telegram-webhook.js) — مركزية هنا عشان أي مسار
// تاني (زي "أضف مصروفك بسرعة" في الداشبورد) يستخدم نفس المنطق ويفضل متوافق معاها دايمًا.
export function normalizeDigits(text) {
  const arabicIndic = '٠١٢٣٤٥٦٧٨٩';
  const persian = '۰۱۲۳۴۵۶۷۸۹';
  return String(text || '')
    .replace(/[٠-٩]/g, (d) => String(arabicIndic.indexOf(d)))
    .replace(/[۰-۹]/g, (d) => String(persian.indexOf(d)));
}
